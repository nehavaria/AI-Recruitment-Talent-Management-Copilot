def hiring_score_csv(result: dict) -> bytes:
    buf = io.StringIO()
    w   = csv.writer(buf)

    cand  = result["candidate"]
    job   = result["job"]
    grade, verdict, _ = _grade_info(result["overall"])

    w.writerow(["Hiring Score Report", _now()])
    w.writerow([])
    w.writerow(["CANDIDATE"])
    w.writerow(["Name",  _safe(cand.get("name"))])
    w.writerow(["Email", _safe(cand.get("email"))])
    w.writerow([])
    w.writerow(["JOB"])
    w.writerow(["Title",      _safe(job.get("job_title"))])
    w.writerow(["Department", _safe(job.get("department"))])
    w.writerow([])
    w.writerow(["SCORES"])
    w.writerow(["Overall Score",       f"{result['overall']}%"])
    w.writerow(["Grade",               grade])
    w.writerow(["Verdict",             verdict])
    w.writerow(["Skill Score (70%)",   f"{result['skill']}%"])
    w.writerow(["Experience Score (20%)", f"{result['experience']}%"])
    w.writerow(["Certification Score (10%)", f"{result['cert']}%"])
    w.writerow([])
    w.writerow(["FORMULA"])
    w.writerow([f"({result['skill']}% × 0.70) + ({result['experience']}% × 0.20) + ({result['cert']}% × 0.10) = {result['overall']}%"])
    w.writerow([])
    w.writerow(["Skills Matched", f"{result['matched']} of {result['total_jd']} required"])

    return buf.getvalue().encode()


def hiring_score_pdf(result: dict) -> bytes:
    cand  = result["candidate"]
    job   = result["job"]
    grade, verdict, clr = _grade_info(result["overall"])

    pdf = _BasePDF()
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(*pdf.DARK)
    pdf.cell(0, 10, "Hiring Score Report", ln=True, align="C")
    pdf.ln(2)

    pdf.big_score(result["overall"], grade, verdict, clr)

    pdf.section_title("Candidate")
    pdf.kv_row("Name",  cand.get("name"))
    pdf.kv_row("Email", cand.get("email"))
    pdf.ln(3)

    pdf.section_title("Job Description")
    pdf.kv_row("Title",      job.get("job_title"))
    pdf.kv_row("Department", job.get("department"))
    pdf.ln(3)

    pdf.section_title("Score Breakdown")
    pdf.score_bar("Overall Score",        result["overall"],    clr)
    pdf.score_bar("Skill Score (70%)",    result["skill"],      pdf.PRIMARY)
    pdf.score_bar("Experience Score (20%)", result["experience"], pdf.BLUE)
    pdf.score_bar("Cert Score (10%)",     result["cert"],       pdf.GREEN)
    pdf.ln(3)

    pdf.section_title("Formula")
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(*pdf.MUTED)
    formula = (
        f"Overall = (Skill x 70%) + (Experience x 20%) + (Cert x 10%)\n"
        f"       = ({result['skill']}% x 0.70) + ({result['experience']}% x 0.20) + ({result['cert']}% x 0.10)\n"
        f"       = {round(result['skill']*0.70,1)} + {round(result['experience']*0.20,1)} + {round(result['cert']*0.10,1)}\n"
        f"       = {result['overall']}%"
    )
    pdf.multi_cell(0, 6, formula)
    pdf.ln(3)

    pdf.section_title("Recommendation")
    recs = {
        "A+": "Strongly Recommend Hiring - Top candidate, schedule interview immediately.",
        "A":  "Recommend Hiring - Strong candidate, proceed to next round.",
        "B":  "Consider with Conditions - Good candidate, may need minor upskilling.",
        "C":  "Borderline - Average fit, consider only if no better options.",
        "D":  "Not Recommended - Significant gaps, does not meet requirements.",
    }
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_text_color(*clr)
    pdf.multi_cell(0, 7, recs.get(grade, "-"))

    return bytes(pdf.output())



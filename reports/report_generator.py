def matching_csv(result: dict) -> bytes:
    """Return CSV bytes for a matching result dict."""
    buf = io.StringIO()
    w   = csv.writer(buf)

    cand   = result["candidate"]
    job    = result["job"]
    skills = result["skills"]
    exp    = result["experience"]
    edu    = result["education"]
    certs  = result["certs"]

    w.writerow(["Candidate Matching Report", _now()])
    w.writerow([])
    w.writerow(["CANDIDATE"])
    w.writerow(["Name",  _safe(cand.get("name"))])
    w.writerow(["Email", _safe(cand.get("email"))])
    w.writerow([])
    w.writerow(["JOB"])
    w.writerow(["Title",      _safe(job.get("job_title"))])
    w.writerow(["Department", _safe(job.get("department"))])
    w.writerow(["Location",   _safe(job.get("location"))])
    w.writerow([])
    w.writerow(["SKILL ANALYSIS"])
    w.writerow(["Match Score",       f"{skills['score']}%"])
    w.writerow(["Matched Skills",    ", ".join(skills["matched"])])
    w.writerow(["Missing Skills",    ", ".join(skills["missing"])])
    w.writerow(["Additional Skills", ", ".join(skills["additional"])])
    w.writerow([])
    w.writerow(["EXPERIENCE"])
    w.writerow(["JD Requires",     exp["jd_level"]])
    w.writerow(["Candidate Level", exp["candidate_level"]])
    w.writerow(["Status",          exp["status"]])
    w.writerow([])
    w.writerow(["EDUCATION"])
    w.writerow(["JD Requires",  edu["jd_requires"]])
    w.writerow(["Candidate Has", edu["candidate_has"]])
    w.writerow(["Status",        edu["status"]])
    w.writerow([])
    w.writerow(["CERTIFICATIONS"])
    if "jd_requires" in certs:
        w.writerow(["JD Requires",  certs["jd_requires"]])
        w.writerow(["Candidate Has", certs["candidate_has"]])
    w.writerow(["Status", certs["status"]])

    return buf.getvalue().encode()


def matching_pdf(result: dict) -> bytes:
    cand   = result["candidate"]
    job    = result["job"]
    skills = result["skills"]
    exp    = result["experience"]
    edu    = result["education"]
    certs  = result["certs"]

    score  = skills["score"]
    grade, verdict, clr = _grade_info(score)

    pdf = _BasePDF()
    pdf.add_page()

    # ── Title ──
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(*pdf.DARK)
    pdf.cell(0, 10, "Candidate Matching Report", ln=True, align="C")
    pdf.ln(2)

    # ── Big score ──
    pdf.big_score(score, grade, verdict, clr)

    # ── Candidate + Job ──
    pdf.section_title("Candidate")
    pdf.kv_row("Name",  cand.get("name"))
    pdf.kv_row("Email", cand.get("email"))
    pdf.ln(3)

    pdf.section_title("Job Description")
    pdf.kv_row("Title",      job.get("job_title"))
    pdf.kv_row("Department", job.get("department"))
    pdf.kv_row("Location",   job.get("location"))
    pdf.ln(3)

    # ── Skill analysis ──
    pdf.section_title("Skill Analysis")
    pdf.score_bar("Match Score", score, clr)
    pdf.ln(2)
    pdf.pill_row("Matched Skills",    skills["matched"],    pdf.GREEN)
    pdf.pill_row("Missing Skills",    skills["missing"],    pdf.RED)
    pdf.pill_row("Additional Skills", skills["additional"], pdf.BLUE)
    pdf.ln(3)

    # ── Experience ──
    pdf.section_title("Experience")
    pdf.kv_row("JD Requires",     exp["jd_level"])
    pdf.kv_row("Candidate Level", exp["candidate_level"])
    pdf.kv_row("Status",          exp["status"])
    pdf.ln(3)

    # ── Education ──
    pdf.section_title("Education")
    pdf.kv_row("JD Requires",  edu["jd_requires"])
    pdf.kv_row("Candidate Has", edu["candidate_has"])
    pdf.kv_row("Status",        edu["status"])
    pdf.ln(3)

    # ── Certifications ──
    pdf.section_title("Certifications")
    if "jd_requires" in certs:
        pdf.kv_row("JD Requires",  certs["jd_requires"])
        pdf.kv_row("Candidate Has", certs["candidate_has"])
    pdf.kv_row("Status", certs["status"])

    return bytes(pdf.output())



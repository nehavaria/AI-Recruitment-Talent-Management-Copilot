def skill_gap_pdf(result: dict) -> bytes:
    cand = result["candidate"]
    job  = result["job"]
    a    = result["analysis"]

    gap  = a["gap_pct"]
    if gap == 0:
        gap_clr = (16, 185, 129)
    elif gap <= 30:
        gap_clr = (245, 158, 11)
    elif gap <= 60:
        gap_clr = (251, 146, 60)
    else:
        gap_clr = (239, 68, 68)

    pdf = _BasePDF()
    pdf.add_page()

    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(*pdf.DARK)
    pdf.cell(0, 10, "Skill Gap Analysis Report", ln=True, align="C")
    pdf.ln(2)

    # ── Gap score ──
    pdf.set_font("Helvetica", "B", 28)
    pdf.set_text_color(*gap_clr)
    pdf.cell(0, 14, f"Skill Gap: {gap}%  |  Match: {a['match_pct']}%", ln=True, align="C")
    pdf.ln(4)

    pdf.section_title("Candidate")
    pdf.kv_row("Name",  cand.get("name"))
    pdf.kv_row("Email", cand.get("email"))
    pdf.ln(3)

    pdf.section_title("Job Description")
    pdf.kv_row("Title",      job.get("job_title"))
    pdf.kv_row("Department", job.get("department"))
    pdf.ln(3)

    pdf.section_title("Summary")
    pdf.score_bar("Match %",    a["match_pct"], pdf.GREEN)
    pdf.score_bar("Skill Gap %", a["gap_pct"],  gap_clr)
    pdf.ln(2)
    pdf.kv_row("Total JD Skills",   str(a["total_jd"]))
    pdf.kv_row("Matched Skills",    str(len(a["matched"])))
    pdf.kv_row("Missing Skills",    str(len(a["missing"])))
    pdf.kv_row("Additional Skills", str(len(a["extra"])))
    pdf.ln(3)

    pdf.section_title("Matched Skills")
    pdf.pill_row("Skills", a["matched"], pdf.GREEN)
    pdf.ln(3)

    pdf.section_title("Missing Skills")
    pdf.pill_row("Skills", a["missing"], pdf.RED)
    pdf.ln(3)

    # ── Learning recommendations table ──
    if a["missing"]:
        pdf.section_title("Learning Recommendations")
        # Table header
        pdf.set_fill_color(*pdf.DARK)
        pdf.set_text_color(255, 255, 255)
        pdf.set_font("Helvetica", "B", 8)

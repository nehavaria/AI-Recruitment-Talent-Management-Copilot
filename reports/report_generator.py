"""Report generator — CSV and PDF for Matching, Hiring Score, and Skill Gap reports."""

import csv
import io
from datetime import datetime

from fpdf import FPDF


# ── Shared helpers ─────────────────────────────────────────────────────────

def _now() -> str:
    return datetime.now().strftime("%Y-%m-%d %H:%M")


def _safe(value) -> str:
    """Convert any value to a clean ASCII string safe for PDF/CSV."""
    text = str(value or "-").replace("\n", " ").strip()
    # Strip non-latin-1 characters so fpdf2 core fonts don't crash
    return text.encode("latin-1", errors="replace").decode("latin-1")


# ══════════════════════════════════════════════════════════════════════════
#  BASE PDF
# ══════════════════════════════════════════════════════════════════════════

class _BasePDF(FPDF):
    BRAND   = "TalentAI · Recruitment Copilot"
    PRIMARY = (124, 58, 237)   # purple
    DARK    = (30,  27,  75)   # dark indigo
    LIGHT   = (241, 245, 249)  # slate-100
    MUTED   = (100, 116, 139)  # slate-500
    GREEN   = (16,  185, 129)
    RED     = (239,  68,  68)
    AMBER   = (245, 158,  11)
    BLUE    = (59,  130, 246)

    def header(self):
        self.set_fill_color(*self.DARK)
        self.rect(0, 0, 210, 22, "F")
        self.set_font("Helvetica", "B", 11)
        self.set_text_color(*self.PRIMARY)
        self.set_xy(10, 6)
        self.cell(0, 10, self.BRAND, ln=False)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(*self.MUTED)
        self.set_xy(0, 6)
        self.cell(200, 10, _now(), align="R")
        self.ln(18)

    def footer(self):
        self.set_y(-14)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(*self.MUTED)
        self.cell(0, 10, f"Page {self.page_no()} - Generated by TalentAI", align="C")

    def section_title(self, text: str) -> None:
        self.set_font("Helvetica", "B", 10)
        self.set_text_color(*self.PRIMARY)
        self.set_fill_color(245, 243, 255)
        self.cell(0, 8, f"  {text}", ln=True, fill=True)
        self.ln(2)

    def kv_row(self, key: str, value: str, color=None) -> None:
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(*self.MUTED)
        self.cell(55, 7, key + ":", ln=False)
        self.set_font("Helvetica", "", 9)
        self.set_text_color(*(color or self.DARK))
        # Use remaining page width so text never overflows
        self.multi_cell(self.epw - 55, 7, _safe(value))

    def score_bar(self, label: str, score: float, color: tuple) -> None:
        """Render a labeled progress bar."""
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(*self.MUTED)
        self.cell(55, 6, label + ":", ln=False)
        # bar background
        x, y = self.get_x(), self.get_y()
        bar_w = 100
        self.set_fill_color(226, 232, 240)
        self.rect(x, y + 1, bar_w, 4, "F")
        # bar fill
        fill_w = round(bar_w * score / 100)
        self.set_fill_color(*color)
        self.rect(x, y + 1, fill_w, 4, "F")
        # score text
        self.set_xy(x + bar_w + 3, y)
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(*color)
        self.cell(20, 6, f"{score}%", ln=True)

    def pill_row(self, label: str, skills: list[str], color: tuple) -> None:
        """Render a label + comma-separated skill list."""
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(*self.MUTED)
        self.cell(55, 6, label + ":", ln=False)
        self.set_font("Helvetica", "", 9)
        self.set_text_color(*color)
        text = ", ".join(skills) if skills else "None"
        # epw = effective page width; subtract label column so content fits
        self.multi_cell(self.epw - 55, 6, text)

    def big_score(self, score: float, grade: str, verdict: str, color: tuple) -> None:
        self.set_font("Helvetica", "B", 32)
        self.set_text_color(*color)
        self.cell(0, 18, f"{score}%  {grade}", ln=True, align="C")
        self.set_font("Helvetica", "", 11)
        self.set_text_color(*self.MUTED)
        self.cell(0, 8, verdict, ln=True, align="C")
        self.ln(4)


def _grade_info(score: float) -> tuple[str, str, tuple]:
    if score >= 85: return "A+", "Excellent",  (16,  185, 129)
    if score >= 70: return "A",  "Strong",      (52,  211, 153)
    if score >= 55: return "B",  "Good",        (245, 158,  11)
    if score >= 40: return "C",  "Average",     (251, 146,  60)
    return              "D",  "Weak",        (239,  68,  68)


